import { copyFile, mkdir, open, readFile, writeFile } from "node:fs/promises"
import { join } from "node:path"
import { beforeAll, describe, expect, it } from "vitest"
import { getKoreaderFileDigest, getKoreaderFileNameDigest } from "./digest"
import { FIXTURES, FIXTURES_DIR } from "./tests/epub"

/**
 * What tools/document-digest.lua answered from KOReader itself: the
 * `util.partialMD5` of every file and the MD5 kosync takes of every file name.
 */
type KoreaderDigests = {
  koreader: string
  files: { name: string; digest: string }[]
  fileNames: { fileName: string; digest: string }[]
}

const KOREADER_DIGESTS_PATH = join(FIXTURES_DIR, "koreader-digests.json")

/** The offsets `util.partialMD5` reads at, as KOReader's frontend/util.lua lists them after 0. */
const KOREADER_SAMPLE_OFFSETS = [
  0, 1024, 4096, 16384, 65536, 262144, 1048576, 4194304, 16777216, 67108864,
  268435456, 1073741824,
]

/**
 * Generated bytes follow a pattern within this distance of a KOReader offset
 * and are zero elsewhere, so a 4 GiB file takes a few KiB on disk.
 */
const PATTERN_RADIUS = 2048

const GIB = 2 ** 30

/** Files generated for KOReader to hash, each size pinning one rule of `util.partialMD5`. */
const GENERATED_FILES: [rule: string, size: number][] = [
  ["an empty file hashes nothing", 0],
  ["a file shorter than a sample is hashed whole", 1],
  ["a file shorter than a sample is hashed whole", 1023],
  ["a file ending with the first sample", 1024],
  ["a second sample cut to one byte", 1025],
  ["a file ending between two offsets", 2048],
  ["a file ending at an offset", 4096],
  ["a third sample cut to one byte", 4097],
  ["the byte after a sample is not read", 5121],
  ["a sample cut short deep in the file", 262144 + 100],
  ["eleven samples below 1 GiB", GIB - 1],
  ["a file ending at the last offset", GIB],
  ["a last sample cut to one byte", GIB + 1],
  ["a whole last sample", GIB + 1024],
  ["nothing past the last sample is read", GIB + 1025],
  ["a size past 32 bits", 4 * GIB + 7],
]

/** File names for KOReader to hash, as kosync's "Filename" method does. */
const FILE_NAMES: [what: string, fileName: string][] = [
  ["ASCII", "Alice's Adventures in Wonderland.epub"],
  ["an é as one code point", "Les Misérables.epub"],
  ["an é as an e and a combining accent", "Les Misérables.epub"],
  ["Japanese", "日本語の本.cbz"],
  ["an emoji", "\u{1F4DA} library.epub"],
]

const generatedByteAt = (position: number) =>
  KOREADER_SAMPLE_OFFSETS.some(
    (offset) => Math.abs(position - offset) < PATTERN_RADIUS,
  )
    ? (position % 251) + 1
    : 0

const generatedBytes = (start: number, end: number) =>
  Uint8Array.from({ length: end - start }, (_, index) =>
    generatedByteAt(start + index),
  )

const readGeneratedFileThroughSliceOnly = (): never => {
  throw new Error("a GeneratedFile is read through slice() only")
}

/**
 * A generated file whose bytes are made only for the ranges read, so a 4 GiB
 * file costs nothing. It is read through `slice()` only, which records each
 * range read.
 */
class GeneratedFile extends Blob {
  readonly readRanges: { start: number; end: number }[] = []

  constructor(readonly generatedSize: number) {
    super([])
  }

  override get size() {
    return this.generatedSize
  }

  override slice(start = 0, end = this.size): Blob {
    const readEnd = Math.min(end, this.size)
    const readStart = Math.min(start, readEnd)

    this.readRanges.push({ start: readStart, end: readEnd })

    return new Blob([generatedBytes(readStart, readEnd)])
  }

  override arrayBuffer(): never {
    return readGeneratedFileThroughSliceOnly()
  }

  override bytes(): never {
    return readGeneratedFileThroughSliceOnly()
  }

  override stream(): never {
    return readGeneratedFileThroughSliceOnly()
  }

  override text(): never {
    return readGeneratedFileThroughSliceOnly()
  }
}

/** Writes a generated file to disk, the zeros as holes. */
const writeGeneratedFile = async (path: string, size: number) => {
  const handle = await open(path, "w")

  try {
    for (const offset of KOREADER_SAMPLE_OFFSETS) {
      const start = Math.max(0, offset - PATTERN_RADIUS)
      const end = Math.min(size, offset + PATTERN_RADIUS)

      if (start < end) {
        await handle.write(generatedBytes(start, end), 0, end - start, start)
      }
    }

    await handle.truncate(size)
  } finally {
    await handle.close()
  }
}

const generatedFileName = (size: number) => `${size}.bin`

/**
 * The inputs tools/document-digest.lua hashes with KOReader: `inputs.json`,
 * listing the files and the file names, and the files under `files/`.
 */
const writeKoreaderInputs = async (dir: string) => {
  const filesDir = join(dir, "files")
  const files: string[] = []

  await mkdir(filesDir, { recursive: true })

  for (const name of FIXTURES) {
    await copyFile(
      join(FIXTURES_DIR, `${name}.epub`),
      join(filesDir, `${name}.epub`),
    )
    files.push(`${name}.epub`)
  }

  for (const [, size] of GENERATED_FILES) {
    await writeGeneratedFile(join(filesDir, generatedFileName(size)), size)
    files.push(generatedFileName(size))
  }

  await writeFile(
    join(dir, "inputs.json"),
    JSON.stringify({
      files,
      fileNames: FILE_NAMES.map(([, fileName]) => fileName),
    }),
  )
}

const readKoreaderDigests = async (): Promise<KoreaderDigests> =>
  JSON.parse(await readFile(KOREADER_DIGESTS_PATH, "utf-8"))

const missingAnswer = (input: string) =>
  new Error(
    `${input}: no KOReader digest in ${KOREADER_DIGESTS_PATH}, run tools/document-digest.lua (see tools/README.md)`,
  )

const emitDir = process.env.KOREADER_DIGEST_EMIT_DIR

if (emitDir) {
  it("writes the inputs for tools/document-digest.lua", () =>
    writeKoreaderInputs(emitDir))
} else {
  describe("KOReader's document digests", () => {
    let koreaderDigests: KoreaderDigests

    beforeAll(async () => {
      koreaderDigests = await readKoreaderDigests()
    })

    const koreaderFileDigestOf = (name: string) => {
      const answer = koreaderDigests.files.find((file) => file.name === name)

      if (!answer) throw missingAnswer(name)

      return answer.digest
    }

    const koreaderFileNameDigestOf = (fileName: string) => {
      const answer = koreaderDigests.fileNames.find(
        (entry) => entry.fileName === fileName,
      )

      if (!answer) throw missingAnswer(fileName)

      return answer.digest
    }

    describe("getKoreaderFileDigest", () => {
      it.each(FIXTURES)("gives KOReader's digest of %s.epub", async (name) => {
        const book = new Blob([
          await readFile(join(FIXTURES_DIR, `${name}.epub`)),
        ])

        expect(await getKoreaderFileDigest(book)).toBe(
          koreaderFileDigestOf(`${name}.epub`),
        )
      })

      it.each(GENERATED_FILES)("%s (%i bytes)", async (_rule, size) => {
        expect(await getKoreaderFileDigest(new GeneratedFile(size))).toBe(
          koreaderFileDigestOf(generatedFileName(size)),
        )
      })

      it("reads at most 12 KiB, however large the file", async () => {
        const file = new GeneratedFile(4 * GIB + 7)

        await getKoreaderFileDigest(file)

        const bytesRead = file.readRanges.reduce(
          (total, { start, end }) => total + end - start,
          0,
        )

        expect(bytesRead).toBeLessThanOrEqual(12 * 1024)
      })
    })

    describe("getKoreaderFileNameDigest", () => {
      it.each(FILE_NAMES)(
        "gives KOReader's digest of a name with %s",
        (_what, fileName) => {
          expect(getKoreaderFileNameDigest(fileName)).toBe(
            koreaderFileNameDigestOf(fileName),
          )
        },
      )
    })
  })
}
